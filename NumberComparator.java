public class NumberComparator {
    public static void compareNumbers() {
        // Объявляем и инициализируем переменные
        int a = -10;
        int b = 5;

        // Проверяем условие и выводим результат
        if (a >= b) {
            System.out.println("a >= b");
        } else {
            System.out.println("a < b");
        }
    }

    public static void main(String[] args) {
        compareNumbers();
    }
}